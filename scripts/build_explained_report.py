add('四个深度状态分别做什么？一笔一笔看计算','''
<p>先说确定的部分：<strong>四个状态分别用于读取深度专家四层特征。</strong>没有代码规定“第一个管 A、第二个管 B”，也没有证据证明它们分别表示近、中、远或背景。</p>
'''+table(['CoVT 中的状态','与它配合的专家特征','计算得到什么'],[['状态 1','专家第 4 层','第一张分数图'],['状态 2','专家第 11 层','第二张分数图'],['状态 3','专家第 17 层','第三张分数图'],['状态 4','专家第 23 层','第四张分数图']])+'''
<p>每个原始状态有 3584 个数。恢复的解码器先用一个小型神经网络把它变成 1024 个数。随后，对于对应专家层的每一个图像位置，都把这 1024 个数与该位置的 1024 维特征逐项相乘，再加起来，得到一个分数。这个运算叫“点积”。</p>
<h3>只用两个数的例子</h3><p>以下是说明性例子，为了能手算，把 1024 维缩成 2 维。假设某个状态转换后是 <strong>(1, 0)</strong>。在同一专家层中，A 位置的特征是 <strong>(2, 5)</strong>，B 位置是 <strong>(1, 9)</strong>：</p>
<div class="walk"><p>A 位置的分数 = 1×2 + 0×5 = <b>2</b><br>B 位置的分数 = 1×1 + 0×9 = <b>1</b></p></div>
<p>这里相同的状态用于所有图像位置，空间差异来自各位置的特征。假设换了一张图，状态仍是 (1, 0)，但 A、B 的特征变成 (1, 5)、(2, 9)，两个分数就变为 1、2。<strong>状态不变，分数图也能随图片改变。</strong>这个例子只解释计算，不规定高分一定更近；实际方向由校准图确定。</p>
<p>四个状态各自得到一张分数图，放大到相同尺寸，再对相同像素取平均，就得到我们展示的 CoVT 深度图。它使用了专家的中间特征，<strong>并没有直接使用专家最终预测的深度图</strong>。专家自己的深度图则另外作为比较结果保存。</p>
<details><summary>需要复现时再看：准确公式与实现差异</summary><p>第 i 个状态为 hᵢ，小型网络输出 tᵢ=W₂ GELU(W₁hᵢ+b₁)+b₂。位置 p 的分数 mᵢ(p)=Σ꜀ tᵢ,꜀ Fᵢ,p,꜀；四张图双线性放大到 256×256 后取平均。网络尺寸为 3584→3584→1024。</p><p>当前固定源码中的点积后没有 softmax，也没有逐图归一化。论文公式包含 softmax，和我们恢复的固定版本代码存在差别；本项目复现结果以经过对照的代码为准。四个状态的逐个语义尚未完成实验验证。</p><p>本地实现：src/covt_pilot/decoder.py、expert.py；源码提交 c3497a325b0fdda4d91ade456a01b0e325ee3150。</p></details>
'''+end('四个状态经过转换后，分别提供读取四层专家特征的数值权重；每个状态本身都不是一张完整深度图。'))

